"""
Toy Dataset for Diffusion Experiments

Loads pre-generated toy data from disk for training diffusion models.
Similar structure to VideoDataset for consistency with train.py.
"""

import json
import numpy as np
import torch
from torch.utils.data import Dataset
from pathlib import Path
from typing import Optional, Dict, Any
from dataclasses import dataclass


@dataclass
class ToyDatasetConfig:
    """Configuration for toy dataset."""
    data_dir: str  # Root directory containing toy data
    embed_dim: int  # Embedding dimension D
    seed: Optional[int] = None

    def __post_init__(self):
        if self.seed is not None:
            np.random.seed(self.seed)
            torch.manual_seed(self.seed)


class ToyDataset(Dataset):
    """
    Toy dataset for diffusion experiments.

    Loads d-dimensional data embedded in D-dimensional space.
    The data is pre-generated by generate_data.py.
    """

    def __init__(
        self,
        config: ToyDatasetConfig,
        split: str = "train",
        train_ratio: float = 0.9,
    ):
        """
        Args:
            config: ToyDatasetConfig object
            split: "train" or "val"
            train_ratio: Ratio of data for training
        """
        self.config = config
        self.split = split
        self.train_ratio = train_ratio

        # Load data
        self.data, self.projection, self.metadata = self._load_data()

        # Split data
        n_total = len(self.data)
        n_train = int(n_total * train_ratio)

        if split == "train":
            self.data = self.data[:n_train]
        elif split == "val":
            self.data = self.data[n_train:]
        else:
            raise ValueError(f"Unknown split: {split}")

    def _load_data(self) -> tuple:
        """Load data from disk."""
        data_dir = Path(self.config.data_dir)
        dim_dir = data_dir / f"D{self.config.embed_dim}"

        if not dim_dir.exists():
            raise FileNotFoundError(
                f"Data directory not found: {dim_dir}\n"
                f"Run 'python -m toy_experiments.generate_data --embed-dims {self.config.embed_dim}' first."
            )

        # Load data
        data_path = dim_dir / "data.npy"
        data = np.load(data_path)

        # Load projection matrix
        proj_path = dim_dir / "projection.npy"
        projection = np.load(proj_path)

        # Load metadata
        meta_path = dim_dir / "metadata.json"
        with open(meta_path, "r") as f:
            metadata = json.load(f)

        return data, projection, metadata

    def __len__(self) -> int:
        return len(self.data)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """
        Get a sample.

        Returns:
            {
                'data': tensor (D,) - embedded data point
                'embed_dim': int - embedding dimension
            }
        """
        sample = torch.from_numpy(self.data[idx]).float()
        return {
            "data": sample,
            "embed_dim": self.config.embed_dim,
        }

    def get_projection(self) -> torch.Tensor:
        """Get the projection matrix used for embedding."""
        return torch.from_numpy(self.projection).float()

    def get_intrinsic_dim(self) -> int:
        """Get the intrinsic dimension d."""
        return self.metadata["intrinsic_dim"]

    def get_embed_dim(self) -> int:
        """Get the embedding dimension D."""
        return self.config.embed_dim

    def get_metadata(self) -> dict:
        """Get dataset metadata."""
        return self.metadata.copy()


def load_toy_dataset(
    data_dir: str,
    embed_dim: int,
    batch_size: int = 256,
    num_workers: int = 0,
    seed: Optional[int] = None,
) -> tuple:
    """
    Convenience function to create train and val dataloaders.

    Args:
        data_dir: Root directory containing toy data
        embed_dim: Embedding dimension D
        batch_size: Batch size
        num_workers: Number of data loading workers
        seed: Random seed

    Returns:
        (train_loader, val_loader)
    """
    from torch.utils.data import DataLoader

    config = ToyDatasetConfig(
        data_dir=data_dir,
        embed_dim=embed_dim,
        seed=seed,
    )

    train_dataset = ToyDataset(config, split="train")
    val_dataset = ToyDataset(config, split="val")

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )

    return train_loader, val_loader


